int main(void)
{
	std::cout << "Init CAN DEV!" << std::endl;

	int ret = canInit();
	if (ret != 0) {
		std::cout << "canInit error!" << std::endl;
	}

	std::this_thread::sleep_for(std::chrono::seconds(10));

	canDeInit();

	return 0;
}